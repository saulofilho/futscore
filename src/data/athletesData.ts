export function getAthleteById(idOrName: string): AthleteProfile | undefined {
  const query = idOrName.toLowerCase().trim();
  return ATHLETES_DATABASE.find(a => 
    a.id === query ||
    a.name.toLowerCase() === query ||
    a.fullName.toLowerCase().includes(query) ||
    (a.nickname && a.nickname.toLowerCase().includes(query))
  );
}
